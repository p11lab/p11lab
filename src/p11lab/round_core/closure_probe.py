"""Isolated inert wheel closure probe. Run only with the sealed W01 interpreter.

This script never imports, installs, or executes candidate code. Its JSON input
is generated by the controller after the archive and wheel bytes are verified.
"""
from __future__ import annotations

import io
import json
import os
import re
from pathlib import Path, PurePosixPath
import stat
import sys
import zipfile
from email.parser import BytesParser
from email.policy import compat32

from packaging.requirements import Requirement
from packaging.specifiers import SpecifierSet
from packaging.tags import compatible_tags, cpython_tags
from packaging.utils import canonicalize_name, parse_wheel_filename
from packaging.version import Version

LIMIT = 40 * 1024 * 1024
MARKERS = {'implementation_name', 'implementation_version', 'os_name', 'platform_machine',
           'platform_release', 'platform_system', 'platform_version', 'python_full_version',
           'platform_python_implementation', 'python_version', 'sys_platform'}


def _wheel(path: str, tags: set, python: Version) -> dict:
    filename = Path(path).name
    name, version, _, wheel_tags = parse_wheel_filename(filename)
    if not wheel_tags.intersection(tags):
        raise ValueError('wheel target incompatibility')
    fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
    with os.fdopen(fd, 'rb') as stream:
        info = os.fstat(stream.fileno())
        if not stat.S_ISREG(info.st_mode) or info.st_size > LIMIT:
            raise ValueError('wheel file type or size')
        data = stream.read(LIMIT + 1)
    with zipfile.ZipFile(io.BytesIO(data)) as z:
        infos = z.infolist()
        if len(infos) > 10000:
            raise ValueError('wheel member limit')
        names = set()
        metadata = []
        for entry in infos:
            n = entry.filename
            parts = PurePosixPath(n)
            if (not n or '\\' in n or '\x00' in n or parts.is_absolute() or '..' in parts.parts
                    or n in names or stat.S_IFMT(entry.external_attr >> 16) not in (0, stat.S_IFREG, stat.S_IFDIR)):
                raise ValueError('unsafe wheel member')
            names.add(n)
            if n.endswith('.dist-info/METADATA'):
                metadata.append(entry)
        if len(metadata) != 1 or metadata[0].file_size > 1024 * 1024:
            raise ValueError('wheel metadata roster')
        message = BytesParser(policy=compat32).parsebytes(z.read(metadata[0]))
    if (len(message.get_all('Name', [])) != 1 or len(message.get_all('Version', [])) != 1
            or canonicalize_name(message.get('Name', '')) != name
            or Version(message.get('Version', '')) != version):
        raise ValueError('wheel metadata identity mismatch')
    requires_python = message.get_all('Requires-Python', [])
    if len(requires_python) > 1 or (requires_python and not SpecifierSet(requires_python[0]).contains(python, prereleases=True)):
        raise ValueError('wheel Python target incompatibility')
    return {'name': str(name), 'version': version,
            'extras': {str(canonicalize_name(v)) for v in message.get_all('Provides-Extra', [])},
            'requirements': [Requirement(v) for v in message.get_all('Requires-Dist', [])]}


def validate(request: dict) -> dict:
    mandatory = {'candidate', 'dependencies', 'target'}
    if not mandatory <= set(request) or set(request) - mandatory - {'roots', 'allow_orphans', 'candidate_extras'}:
        raise ValueError('invalid closure request')
    if type(request.get('allow_orphans', False)) is not bool:
        raise ValueError('invalid orphan policy')
    target = request['target']
    if set(target) != {'python_version', 'platforms', 'abis', 'marker_environment'}:
        raise ValueError('invalid target')
    env = target['marker_environment']
    if (type(env) is not dict or set(env) != MARKERS or any(type(v) is not str for v in env.values())
            or env['implementation_name'] != 'cpython' or env['python_version'] != target['python_version']):
        raise ValueError('invalid marker target')
    python = Version(env['python_full_version'])
    if '.'.join(map(str, python.release[:2])) != target['python_version']:
        raise ValueError('inconsistent Python target')
    platforms, abis = target['platforms'], target['abis']
    if (type(platforms) is not list or not platforms or type(abis) is not list or not abis
            or any(type(v) is not str or not v for v in platforms + abis)):
        raise ValueError('invalid target tags')
    pyver = (python.release[0], python.release[1])
    if (env['os_name'] != 'posix' or env['sys_platform'] != 'linux' or env['platform_system'] != 'Linux'
            or env['platform_machine'] != 'x86_64' or abis != ['cp%d%d' % pyver]
            or any(not re.fullmatch(r'(?:linux_x86_64|manylinux_[0-9]+_[0-9]+_x86_64|manylinux(?:1|2010|2014)_x86_64)', p)
                   for p in platforms)):
        raise ValueError('unsupported target platform or ABI')
    tags = set(cpython_tags(python_version=pyver, abis=abis, platforms=platforms))
    tags.update(compatible_tags(python_version=pyver, interpreter='cp%d%d' % pyver, platforms=platforms))
    if type(request['dependencies']) is not list or len(request['dependencies']) > 10000:
        raise ValueError('invalid dependency roster')
    candidate = _wheel(request['candidate'], tags, python) if request['candidate'] is not None else None
    wheels = {}
    for path in request['dependencies']:
        item = _wheel(path, tags, python)
        if item['name'] in wheels or (candidate is not None and item['name'] == candidate['name']):
            raise ValueError('ambiguous dependency')
        wheels[item['name']] = item
    seen = set()
    reached = set()
    pending = [(candidate, '')] if candidate is not None else []
    extras = request.get('candidate_extras', [])
    if type(extras) is not list or any(type(x) is not str or not x for x in extras):
        raise ValueError('invalid candidate extras')
    if candidate is not None:
        pending.extend((candidate, str(canonicalize_name(extra))) for extra in extras)
    elif extras:
        raise ValueError('build roots carry their own extras')
    if candidate is None:
        roots = request.get('roots')
        if type(roots) is not list or not roots or len(roots) > 10000:
            raise ValueError('invalid build roots')
        for value in roots:
            requirement = Requirement(value)
            if requirement.url:
                raise ValueError('direct URL requirement unsupported')
            if requirement.marker is not None and not requirement.marker.evaluate(dict(env, extra='')):
                continue
            name = str(canonicalize_name(requirement.name))
            if name not in wheels:
                raise ValueError('missing dependency: ' + name)
            item = wheels[name]
            if not requirement.specifier.contains(item['version'], prereleases=True):
                raise ValueError('dependency version mismatch: ' + name)
            reached.add(name)
            pending.append((item, ''))
            pending.extend((item, str(canonicalize_name(v))) for v in requirement.extras)
    elif 'roots' in request:
        raise ValueError('unexpected build roots')
    while pending:
        item, extra = pending.pop()
        if extra and extra not in item['extras']:
            raise ValueError('requested extra not provided')
        key = (item['name'], extra)
        if key in seen:
            continue
        seen.add(key)
        for requirement in item['requirements']:
            if requirement.url:
                raise ValueError('direct URL requirement unsupported')
            marker_env = dict(env, extra=extra)
            if requirement.marker is not None and not requirement.marker.evaluate(marker_env):
                continue
            name = str(canonicalize_name(requirement.name))
            if name not in wheels and (candidate is None or name != candidate['name']):
                raise ValueError('missing dependency: ' + name)
            dependency = wheels[name] if name in wheels else candidate
            if not requirement.specifier.contains(dependency['version'], prereleases=True):
                raise ValueError('dependency version mismatch: ' + name)
            if name in wheels:
                reached.add(name)
            pending.append((dependency, ''))
            pending.extend((dependency, str(canonicalize_name(v))) for v in requirement.extras)
    if reached != set(wheels) and not request.get('allow_orphans', False):
        raise ValueError('orphan dependency wheel')
    return {'candidate': candidate['name'] if candidate else None,
            'dependencies': sorted(reached), 'available': sorted(wheels),
            'status': 'static-closure-verified'}


def main() -> int:
    try:
        raw = sys.stdin.buffer.read(2 * 1024 * 1024 + 1)
        if len(raw) > 2 * 1024 * 1024:
            raise ValueError('closure request byte bound')
        result = validate(json.loads(raw))
        print(json.dumps(result, sort_keys=True))
        return 0
    except Exception as error:
        print('closure validation failed: ' + str(error), file=sys.stderr)
        return 2


if __name__ == '__main__':
    raise SystemExit(main())
